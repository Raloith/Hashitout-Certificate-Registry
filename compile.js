// Compiles contracts/CertificateRegistry.sol and writes artifacts/ + docs/contract-artifact.js
const fs = require('fs'); const solc = require('solc');
const source = fs.readFileSync(__dirname + '/contracts/CertificateRegistry.sol', 'utf8');
const input = { language: 'Solidity', sources: { 'CertificateRegistry.sol': { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } };
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errs = (out.errors || []).filter(e => e.severity === 'error');
(out.errors || []).forEach(e => console.log(e.formattedMessage));
if (errs.length) process.exit(1);
const c = out.contracts['CertificateRegistry.sol'].CertificateRegistry;
const art = { contractName: 'CertificateRegistry', compiler: solc.version(), abi: c.abi, bytecode: '0x' + c.evm.bytecode.object };
fs.mkdirSync(__dirname + '/artifacts', { recursive: true });
fs.writeFileSync(__dirname + '/artifacts/CertificateRegistry.json', JSON.stringify(art, null, 2));
fs.mkdirSync(__dirname + '/docs', { recursive: true });
fs.writeFileSync(__dirname + '/docs/contract-artifact.js', '// Auto-generated by compile.js - do not edit\nwindow.CERT_ARTIFACT = ' + JSON.stringify(art) + ';\n');
console.log('Compiled OK with solc', solc.version(), '- bytecode bytes:', c.evm.bytecode.object.length / 2);
